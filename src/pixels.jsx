// Three hamsters studying together, for the Study Mode scenario screen -- it
// stands where the dial does in Simulation Mode, which has a score to report
// and this does not.
//
// Same 2px grid as the rest of the art, and everything stands on one floor
// line at y36: a pile of books at each end, the three hamsters between them,
// the slate and the lamp behind. Nothing sits on top of anything else.
const FLOOR = 36;

// MiniHamster's pattern rebased to its own origin. `flip` mirrors it about
// its own width so a pair can face each other.
function StudyHamster({ x, y = FLOOR - 10, flip = false }) {
  return (
    <g
      transform={
        flip ? `translate(${x + 12} ${y}) scale(-1 1)` : `translate(${x} ${y})`
      }
    >
      <rect x="2" y="2" width="8" height="2" fill="#F2C94C" />
      <rect x="0" y="4" width="12" height="2" fill="#F2C94C" />
      <rect x="0" y="6" width="12" height="2" fill="#F2C94C" />
      <rect x="2" y="8" width="8" height="2" fill="#F2C94C" />
      <rect x="8" y="4" width="2" height="2" fill="#1A1A2E" />
      {/* ears last, so they paint over the body rather than behind it */}
      <rect x="0" y="0" width="2" height="2" fill="#EF8B2C" />
      <rect x="8" y="0" width="2" height="2" fill="#EF8B2C" />
    </g>
  );
}

// A pile of closed books, stacked up from the floor. Each book is a coloured
// slab with a pale strip for the page edge; the strip and a two-unit jog
// alternate down the pile so it reads as hand-stacked rather than as one
// shape repeated.
//
// Not an open book: pages splayed either side of a centre spine sit right
// under a head and read as a collar and lapels -- the hamsters looked like
// they were wearing suits.
function BookStack({ x, colours }) {
  return (
    <g>
      {colours.map((colour, i) => {
        const y = FLOOR - (i + 1) * 4;
        const jog = i % 2 === 0 ? 0 : 2;
        const w = 22 - jog * 2;
        return (
          <g key={i}>
            <rect x={x + jog} y={y} width={w} height="4" fill={colour} />
            <rect
              x={i % 2 === 0 ? x + w - 4 : x + jog}
              y={y}
              width="4"
              height="4"
              fill="#E8E8E8"
            />
          </g>
        );
      })}
    </g>
  );
}

